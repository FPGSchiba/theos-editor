//! The `Server`: the shared state and the MCP handler around the tool router.

use std::sync::{Arc, Mutex};

use rmcp::model::{
    GetPromptRequestParams, GetPromptResponse, Implementation, ListPromptsResult,
    PaginatedRequestParams, ServerCapabilities, ServerConfig,
};
use rmcp::service::RequestContext;
use rmcp::{ErrorData, RoleServer};
use rmcp::{ServerHandler, tool_handler};

use crate::prompts;
use crate::state::State;
use crate::tools;

/// What the client is told about the server.
const INSTRUCTIONS: &str = "Read-only access to a Theos content project: records, their \
links, the lore ledger and the project's guides. Nothing here changes a project file; \
changes are proposed to the user. Every result flags what needs care: a truth with target \
`never` is marked `never` and is not to be put in any prompt or text a player sees, and a \
record marked `locked` is approved content that can be read but not changed.";

/// The MCP server. Clones share one state.
#[derive(Clone)]
pub struct Server {
    /// The project; a tool locks it, runs synchronously and releases it before it returns.
    pub state: Arc<Mutex<State>>,
}

impl Server {
    /// A server over `state`.
    #[must_use]
    pub fn new(state: State) -> Server {
        Server {
            state: Arc::new(Mutex::new(state)),
        }
    }
}

#[tool_handler(router = tools::router())]
#[expect(
    clippy::unused_async_trait_impl,
    reason = "the async methods of `ServerHandler` are generated by `tool_handler`"
)]
impl ServerHandler for Server {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(
            ServerCapabilities::builder()
                .enable_tools()
                .enable_prompts()
                .build(),
        )
        .with_server_info(Implementation::new("theos-mcp", env!("CARGO_PKG_VERSION")))
        .with_instructions(INSTRUCTIONS)
    }

    async fn list_prompts(
        &self,
        _request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListPromptsResult, ErrorData> {
        Ok(ListPromptsResult::with_all_items(prompts::list(
            &self.state,
        )))
    }

    async fn get_prompt(
        &self,
        request: GetPromptRequestParams,
        _context: RequestContext<RoleServer>,
    ) -> Result<GetPromptResponse, ErrorData> {
        prompts::get(&self.state, &request.name).map(GetPromptResponse::from)
    }
}
