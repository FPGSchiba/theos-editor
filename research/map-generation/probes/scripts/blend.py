"""Probe 8: interpolate every numeric recipe value between two recipes of the same structure
and run each step with the same seed.

  python scripts/blend.py <a.yaml> <b.yaml> <out_dir> --steps 5 --seeds 1 2 --sheet-prefix PATH

Writes the blended recipes to recipes/p8-blend/ (t = 0 .. 1), runs them, and reports how much
the map changes per step: RMS height change, height correlation, how far settlements move.
Counts (settlement, resource, site, ruin counts; provinces; plutons) are rounded to integers.
"""
import argparse, copy, json, sys, time
from pathlib import Path
import numpy as np
import yaml
sys.path.insert(0, str(Path(__file__).parent))
from probe import CAVEAT, banner_sheet, terrain_metrics


def lerp(a, b, t, key=""):
    if isinstance(a, dict) and isinstance(b, dict):
        return {k: lerp(a.get(k, 0 if k in b and isinstance(b[k], (int, float)) else b.get(k)),
                        b.get(k, 0 if isinstance(a.get(k), (int, float)) else a.get(k)), t, k)
                for k in list(a) + [k for k in b if k not in a]}
    if isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        return [lerp(x, y, t, key) for x, y in zip(a, b)]
    if isinstance(a, bool) or isinstance(b, bool) or not isinstance(a, (int, float)) or not isinstance(b, (int, float)):
        return a if t < 0.5 else b
    v = a + (b - a) * t
    return int(round(v)) if isinstance(a, int) and isinstance(b, int) else float(v)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("a"); ap.add_argument("b"); ap.add_argument("out")
    ap.add_argument("--steps", type=int, default=5); ap.add_argument("--seeds", type=int, nargs="+", default=[1, 2])
    ap.add_argument("--sheet-prefix"); ap.add_argument("--recipes-dir", default="recipes/p8-blend")
    a = ap.parse_args()
    print(CAVEAT)
    from theos_maps import core
    from theos_maps.run import run_one
    A, B = core.load_recipe(a.a), core.load_recipe(a.b)
    assert [s["stage"] for s in A["pipeline"]] == [s["stage"] for s in B["pipeline"]], "stage lists differ"
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    rdir = Path(a.recipes_dir); rdir.mkdir(parents=True, exist_ok=True)
    ts = np.linspace(0, 1, a.steps)
    report = []
    for seed in a.seeds:
        prev, tiles, labels = None, [], []
        for t in ts:
            R = lerp(copy.deepcopy(A), B, float(t))
            R["name"] = f"p8-blend-t{int(round(t * 100)):03d}"
            R["pipeline"] = [s for s in R["pipeline"] if s["stage"] != "constraints"]
            (rdir / f"{R['name']}.yaml").write_text(
                f"# Probe 8: generated by scripts/blend.py, t = {t:.2f} between {Path(a.a).name} and {Path(a.b).name}\n"
                + yaml.safe_dump(R, sort_keys=False, default_flow_style=None))
            t0 = time.time()
            w, images, _ = run_one(R, seed, out / f"{R['name']}_s{seed}", (), None, False)
            sett = {f["id"]: f["yx"] for f in w["features"] if f["kind"] == "settlement"}
            row = {"seed": seed, "t": round(float(t), 2), "run_s": round(time.time() - t0, 1),
                   "relief_m": w.summary["elevation_m"]["relief"], "lake_pct": w.summary["lake_pct"],
                   "veg_pct": w.summary["vegetation_cover_pct"], "rivers_pct": w.summary["rivers_pct"],
                   "slope_p90_deg": terrain_metrics(w)["slope_deg"]["p90"],
                   "settlements": len(sett), "road_km": round(sum(w.summary.get("roads", {}).values()), 1)}
            cur = {"z": w["z"].copy(), "sett": sett, "river": w["river"].copy(), "lake": w["lake"].copy(),
                   "km": w["shape"][1] / R["size_km"][1]}
            if prev is not None:
                zc = float(np.corrcoef(prev["z"].ravel(), cur["z"].ravel())[0, 1])
                row["step_height_corr"] = round(zc, 3)
                row["step_height_rms_m"] = round(float(np.sqrt(((cur["z"] - prev["z"]) ** 2).mean())), 1)
                both = (prev["river"] | cur["river"]).sum()
                row["step_river_overlap"] = round(float((prev["river"] & cur["river"]).sum() / max(both, 1)), 3)
                bl = (prev["lake"] | cur["lake"]).sum()
                row["step_lake_overlap"] = round(float((prev["lake"] & cur["lake"]).sum() / max(bl, 1)), 3)
                common = [k for k in cur["sett"] if k in prev["sett"]]
                mv = [float(np.hypot(*(np.array(cur["sett"][k]) - np.array(prev["sett"][k]))) / cur["km"]) for k in common]
                row["step_settlement_move_km"] = {"median": round(float(np.median(mv)), 2), "max": round(max(mv), 2)} if mv else None
            prev = cur
            report.append(row)
            tiles.append(images[0]); labels.append(f"seed {seed}, t = {t:.2f}")
            print(json.dumps(row))
        if a.sheet_prefix:
            size = banner_sheet(tiles, labels, f"{a.sheet_prefix}_s{seed}_contact.png", cols=3, tile_w=440,
                                title=f"p8 blend: {Path(a.a).stem} (t=0) -> {Path(a.b).stem} (t=1), seed {seed}")
            print("sheet", size, "bytes")
    (out / "p8-blend_results.json").write_text(json.dumps(report, indent=1))


if __name__ == "__main__":
    main()
